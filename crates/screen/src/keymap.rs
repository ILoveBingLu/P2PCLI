/// macOS 虚拟键码
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub fn mac(code: &str) -> Option<u16> {
    TABLE.iter().find(|(c, ..)| *c == code).map(|&(_, m, _)| m).filter(|&m| m != 0xFFFF)
}

/// Windows 扫描码：(扫描码, 是不是扩展键)
#[cfg_attr(not(windows), allow(dead_code))]
pub fn windows(code: &str) -> Option<(u16, bool)> {
    TABLE.iter().find(|(c, ..)| *c == code).map(|&(_, _, w)| (w & 0xFF, w & 0xFF00 == 0xE000))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookup() {
        assert_eq!(mac("KeyA"), Some(0));
        assert_eq!(mac("PrintScreen"), None);
        assert_eq!(windows("ArrowUp"), Some((0x48, true)));
        assert_eq!(windows("KeyA"), Some((0x1E, false)));
        assert_eq!(mac("Nope"), None);
        // 每个 code 只出现一次
        let mut codes: Vec<_> = TABLE.iter().map(|(c, ..)| *c).collect();
        codes.sort();
        let n = codes.len();
        codes.dedup();
        assert_eq!(codes.len(), n);
    }
}
